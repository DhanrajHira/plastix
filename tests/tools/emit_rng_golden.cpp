// Emits the RNG golden vectors that pin plastix's counter-based samplers.
//
// The samplers are pure functions of (Seed, Counter): a connection at id `c`
// always draws the same value regardless of scheduling, host or device, which
// makes them reproducible outside C++ and lets plastax pin the same contract.
//
// Modes (argv[1], default "uniform"):
//   uniform  -> UniformReal over two ranges (raw float32 bit patterns, hex).
//   normal   -> NormalReal (raw float32 bit patterns, hex).
//   kofn     -> SampleKofN (exact integer index lists).
//
// The values reflect whatever PLASTIX_RNG_ENGINE this tool was built with, so
// the emitted file is per-engine. Regenerate, e.g.:
//   cmake --build build --target emit_rng_golden
//   build/tests/tools/emit_rng_golden uniform > tests/golden/rng_uniform_philox.json
//   build/tests/tools/emit_rng_golden normal  > tests/golden/rng_normal.json
//   build/tests/tools/emit_rng_golden kofn    > tests/golden/rng_kofn.json

#include <plastix/random.hpp>

#include <cstdint>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

namespace {

uint32_t Bits(float F) {
  uint32_t B;
  std::memcpy(&B, &F, sizeof(B));
  return B;
}

struct Range {
  const char *Name;
  float Min;
  float Max;
};

// Two ranges spanning both branches of the range mapping: (-1, 1) straddles
// zero, (2, 5) is same-sign. A port that only checks one branch will pass while
// being wrong for the other.
constexpr Range Ranges[] = {
    {"signed", -1.0f, 1.0f},
    {"positive", 2.0f, 5.0f},
};

const char *EngineName() {
#if PLASTIX_RNG_ENGINE == PLASTIX_RNG_MINSTD
  return "minstd";
#else
  return "philox";
#endif
}

// Seeds: the small values the examples use, plus boundary and high-entropy
// ones. Counters: a dense low range (the first edges of any layer) plus a
// sparse high range, since real connection ids run to millions.
std::vector<uint64_t> SeedGrid() {
  return {0u, 1u, 2u, 7u, 42u, 12345u, 0xDEADBEEFull, 0xFFFFFFFFFFFFFFFFull};
}

std::vector<uint64_t> CounterGrid() {
  std::vector<uint64_t> Counters;
  for (uint64_t C = 0; C < 32; ++C)
    Counters.push_back(C);
  for (uint64_t C : {1000ull, 65535ull, 65536ull, 1000000ull, 16777217ull})
    Counters.push_back(C);
  return Counters;
}

void EmitHeader(const char *Kind) {
  std::printf("{\n");
  std::printf("  \"_comment\": \"plastix RNG reference values. Generated by "
              "tests/tools/emit_rng_golden.cpp; do not hand-edit.\",\n");
  std::printf("  \"source\": \"include/plastix/random.hpp\",\n");
  std::printf("  \"engine\": \"%s\",\n", EngineName());
  std::printf("  \"kind\": \"%s\",\n", Kind);
}

int EmitUniform() {
  EmitHeader("uniform");
  std::printf("  \"ranges\": {\n");
  for (size_t R = 0; R < std::size(Ranges); ++R)
    std::printf("    \"%s\": [%.1f, %.1f]%s\n", Ranges[R].Name,
                static_cast<double>(Ranges[R].Min),
                static_cast<double>(Ranges[R].Max),
                R + 1 < std::size(Ranges) ? "," : "");
  std::printf("  },\n");
  std::printf("  \"samples\": [\n");
  bool First = true;
  for (uint64_t S : SeedGrid()) {
    for (uint64_t C : CounterGrid()) {
      if (!First)
        std::printf(",\n");
      First = false;
      std::printf("    {\"seed\": %llu, \"counter\": %llu",
                  static_cast<unsigned long long>(S),
                  static_cast<unsigned long long>(C));
      for (const Range &R : Ranges)
        std::printf(", \"%s\": \"%08x\"", R.Name,
                    Bits(plastix::UniformReal(S, C, R.Min, R.Max)));
      std::printf("}");
    }
  }
  std::printf("\n  ]\n}\n");
  return 0;
}

int EmitNormal() {
  EmitHeader("normal");
  std::printf("  \"samples\": [\n");
  bool First = true;
  for (uint64_t S : SeedGrid()) {
    for (uint64_t C : CounterGrid()) {
      if (!First)
        std::printf(",\n");
      First = false;
      std::printf("    {\"seed\": %llu, \"counter\": %llu, \"normal\": \"%08x\"}",
                  static_cast<unsigned long long>(S),
                  static_cast<unsigned long long>(C),
                  Bits(plastix::NormalReal(S, C)));
    }
  }
  std::printf("\n  ]\n}\n");
  return 0;
}

int EmitKofN() {
  EmitHeader("kofn");
  // A spread of (N, K): tiny, K == N (full permutation as a set), and a wider
  // draw that exercises the sorted-insert path repeatedly.
  struct Case {
    uint32_t N;
    uint32_t K;
  };
  constexpr Case Cases[] = {{4, 2}, {8, 3}, {10, 10}, {64, 5}, {256, 16}};

  std::printf("  \"samples\": [\n");
  bool First = true;
  for (uint64_t S : {0ull, 1ull, 7ull, 42ull, 0xDEADBEEFull}) {
    for (uint64_t C : {0ull, 1ull, 5ull, 100ull, 65536ull}) {
      for (const Case &Cs : Cases) {
        if (!First)
          std::printf(",\n");
        First = false;
        uint32_t Out[256];
        plastix::SampleKofN(S, C, Cs.N, Cs.K, Out);
        std::printf("    {\"seed\": %llu, \"counter\": %llu, \"n\": %u, "
                    "\"k\": %u, \"out\": [",
                    static_cast<unsigned long long>(S),
                    static_cast<unsigned long long>(C), Cs.N, Cs.K);
        for (uint32_t I = 0; I < Cs.K; ++I)
          std::printf("%s%u", I ? ", " : "", Out[I]);
        std::printf("]}");
      }
    }
  }
  std::printf("\n  ]\n}\n");
  return 0;
}

} // namespace

int main(int Argc, char **Argv) {
  const std::string Mode = Argc > 1 ? Argv[1] : "uniform";
  if (Mode == "uniform")
    return EmitUniform();
  if (Mode == "normal")
    return EmitNormal();
  if (Mode == "kofn")
    return EmitKofN();
  std::fprintf(stderr, "unknown mode '%s' (want uniform|normal|kofn)\n",
               Mode.c_str());
  return 2;
}
